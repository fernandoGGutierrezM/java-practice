

public class mathU {
    public static void main(String[] args){

        //FOR A GOOD PI NUMBER
        System.out.print("num pi: ");
        System.out.println(Math.PI);

        //for euler
        System.out.print("num e: ");
        System.out.println(Math.E);

        //powers 2^3
        System.out.print("power 2^3: ");
        System.out.println(Math.pow(2,3));

        System.out.print("absolute value of -9: ");
        System.out.println(Math.abs(-9));
        
        System.out.print("square root of 9: ");
        System.out.println(Math.sqrt(9));

        System.out.print("round 9.9: ");
        System.out.println(Math.round(9.9));

        System.out.println("floor and ceil of 9.5: ");
        System.out.print(Math.floor(9.5));
        System.out.print('\n');
        System.out.print(Math.ceil(9.5));

    }
    
}
